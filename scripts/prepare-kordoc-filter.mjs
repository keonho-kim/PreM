// Purpose: Bind native image screening to the exact filter shipped by the pinned Kordoc package.
// Pattern: Build-time adapter for a non-public export; fail closed on upstream layout/version changes.
// Usage: prepare-document-runtime imports this; no discovery or package installation at runtime.
// Related: runtime/kordoc/package-lock.json, backend/tools/reference-previews.mjs.
import fs from 'node:fs/promises';
import path from 'node:path';
export async function prepareKordocFilter(runtime) {
  const folder = path.join(runtime, 'kordoc/node_modules/kordoc');
  const pkg = JSON.parse(await fs.readFile(path.join(folder, 'package.json'), 'utf8'));
  if (pkg.version !== '4.24.83')
    throw new Error('Review Kordoc image-filter adapter before upgrading');
  const source = await fs.readFile(path.join(folder, 'dist/index.js'), 'utf8');
  const imports = [...source.matchAll(/import\s*\{([^}]+)\}\s*from\s*"(\.\/[^"\n]+)"/g)].filter(
    (entry) => /\bdropBlankImages\b/.test(entry[1]),
  );
  if (imports.length !== 1 || !/^\.\/chunk-[\w-]+\.js$/.test(imports[0][2]))
    throw new Error('Kordoc blank-image filter export was not found');
  const module = `kordoc/node_modules/kordoc/dist/${imports[0][2].slice(2)}`;
  const code = await fs.readFile(path.join(runtime, module), 'utf8');
  if (!code.includes('async function dropBlankImages('))
    throw new Error('Unexpected Kordoc image filter');
  await fs.writeFile(
    path.join(runtime, 'kordoc-image-filter.mjs'),
    `// Generated by scripts/prepare-kordoc-filter.mjs; do not edit.\n// Uses Kordoc ${pkg.version}'s own filter without reimplementing its pixel rules.\nimport { dropBlankImages } from './${module}';\nexport async function isBlankImage(bytes, mimeType) {\n  const images = [{filename:'candidate', data:bytes, mimeType}];\n  const warnings = [];\n  await dropBlankImages([{type:'image', text:'candidate'}], images, warnings);\n  if (warnings.length) throw new Error('image_filter_unavailable');\n  return images.length === 0;\n}\n`,
  );
  return ['kordoc-image-filter.mjs', module];
}
